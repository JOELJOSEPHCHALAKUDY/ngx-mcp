import { chromium } from '/Users/joeljoseph/Desktop/Personal Work/ai-experiments-apps/angular-mcp-compiler/node_modules/playwright/index.mjs';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {installFixture} from './fixture.mjs';
const out = new URL('./', import.meta.url);
const report={phase:'source-only DOM reference', compilerSourceRead:false, compilerManifestRead:false, sourcePatches:[], startedAt:new Date().toISOString(), operations:[], boundaryChecks:[], errors:[]};
let browser;
try {
 browser=await chromium.launch({headless:true});
 const page=await browser.newPage();
 page.on('pageerror',error=>report.errors.push(error.message));
 const fixture=await installFixture(page);
 const snapshot=async()=>({rows:await page.locator('.todo-list li').evaluateAll(rows=>rows.map(row=>({title:row.querySelector('label').textContent,completed:row.classList.contains('completed'),checked:row.querySelector('input').checked}))),footer:await page.locator('.todo-count').textContent().catch(()=>null),input:await page.locator('.new-todo').inputValue(),fixture:structuredClone(fixture.todos)});
 await page.goto('http://127.0.0.1:4341/',{waitUntil:'networkidle'});
 await page.locator('.todo-list li').nth(2).waitFor();
 assert.deepEqual(await page.locator('.todo-list li label').allTextContents(),['Read fixture article','Clean fixture inbox','Reserve fixture table']);
 assert.equal(await page.locator('.todo-list li').nth(2).locator('input').isChecked(),true);
 report.operations.push({id:'list_todos',pass:true,observed:await snapshot(),calls:structuredClone(fixture.calls)});
 let start=fixture.calls.length;
 await page.locator('input.new-todo').fill('Frozen holdout task');
 await page.locator('input.new-todo').press('Enter');
 await page.getByText('Frozen holdout task',{exact:true}).waitFor();
 assert.deepEqual(fixture.calls[start],{method:'POST',url:'http://localhost:3000/todos',body:{title:'Frozen holdout task',complete:false}});
 assert.equal(await page.locator('.new-todo').inputValue(),'');
 assert.equal(await page.locator('.todo-list li').count(),4);
 report.operations.push({id:'add_todo',pass:true,observed:await snapshot(),calls:fixture.calls.slice(start)});
 start=fixture.calls.length;
 await page.locator('.todo-list li').filter({hasText:'Read fixture article'}).locator('input.toggle').click();
 assert.equal(fixture.todos.find(todo=>todo.id===1).complete,true);
 assert.equal(await page.locator('.todo-list li').filter({hasText:'Read fixture article'}).getAttribute('class'),'completed');
 assert.deepEqual(fixture.calls[start],{method:'PUT',url:'http://localhost:3000/todos/1',body:{id:1,title:'Read fixture article',complete:true}});
 report.operations.push({id:'toggle_todo_complete',pass:true,observed:await snapshot(),calls:fixture.calls.slice(start)});
 start=fixture.calls.length;
 const removeRow=page.locator('.todo-list li').filter({hasText:'Clean fixture inbox'});
 await removeRow.hover(); await removeRow.locator('button.destroy').click();
 await page.waitForFunction(()=>document.querySelectorAll('.todo-list li').length===3);
 assert.equal(fixture.todos.some(todo=>todo.id===2),false);
 assert.deepEqual(fixture.calls[start],{method:'DELETE',url:'http://localhost:3000/todos/2',body:null});
 report.operations.push({id:'delete_todo',pass:true,observed:await snapshot(),calls:fixture.calls.slice(start)});
 start=fixture.calls.length;
 await page.locator('.todo-list li').filter({hasText:'Read fixture article'}).locator('input.toggle').click();
 assert.equal(fixture.todos.find(todo=>todo.id===1).complete,false);
 report.boundaryChecks.push({id:'toggle_again_reverses',pass:true,calls:fixture.calls.slice(start)});
 start=fixture.calls.length;
 await page.locator('input.new-todo').press('Enter');
 await page.waitForFunction(()=>document.querySelectorAll('.todo-list li').length===4);
 assert.deepEqual(fixture.calls[start].body,{title:'',complete:false});
 report.boundaryChecks.push({id:'blank_title_source_has_no_guard',pass:true,calls:fixture.calls.slice(start)});
 await page.screenshot({path:new URL('reference.png',out).pathname,fullPage:true});
 report.final=await snapshot(); report.calls=fixture.calls;
 report.pass=report.operations.length===4&&report.operations.every(operation=>operation.pass)&&report.errors.length===0;
} catch(error) {report.pass=false;report.failure={message:error.message,stack:error.stack};} finally {
 if(browser)await browser.close();
 report.finishedAt=new Date().toISOString();
 await fs.writeFile(new URL('reference-results.json',out),JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify({pass:report.pass,operations:report.operations.map(({id,pass})=>({id,pass})),boundaryChecks:report.boundaryChecks,failure:report.failure},null,2));
}
